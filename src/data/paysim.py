"""PaySim mobile-money loader.

Builds an ACCOUNT graph (not a transaction graph): nameOrig -> nameDest edges.
This is the cleanest of the three for ring detection, because accounts are
already first-class and rings are literally connected components of accounts.

Expected: one CSV in data/raw/paysim/ with columns
  step, type, amount, nameOrig, oldbalanceOrg, newbalanceOrig,
  nameDest, oldbalanceDest, newbalanceDest, isFraud, isFlaggedFraud
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from src.data.base import GraphBundle
from src.utils.config import get_logger, raw_dir

log = get_logger(__name__)

BAL_COLS = ["oldbalanceOrg", "newbalanceOrig", "oldbalanceDest", "newbalanceDest"]


def _balance_features(df: pd.DataFrame, n_accounts: int) -> pd.DataFrame:
    """Balance-derived features that expose mule behaviour.

    A mule account is money passing straight through: a large deposit arrives
    and the balance is emptied almost immediately. Transaction aggregates alone
    cannot see this — an account that receives 1,00,000 and keeps it looks
    identical to one that receives 1,00,000 and forwards it within the hour.
    The balance columns are what separate them.

    Returns a DataFrame indexed 0..n_accounts-1.
    """
    missing = [c for c in BAL_COLS if c not in df.columns]
    if missing:
        log.warning("balance columns missing (%s); skipping mule features", missing)
        return pd.DataFrame(index=np.arange(n_accounts))

    d = df
    eps = 1.0  # guards division on zero-balance accounts

    # --- as sender -------------------------------------------------------
    # fraction of the balance moved out in one transaction. ~1.0 means the
    # account was drained, which is the signature of both the victim of a
    # takeover and the mule forwarding everything on.
    drain = (d["amount"] / (d["oldbalanceOrg"] + eps)).clip(0, 2)
    emptied = ((d["newbalanceOrig"] < 1.0) & (d["oldbalanceOrg"] > 1.0)).astype(float)
    # PaySim's ledger does not always balance; the residual is itself signal
    # because fraudulent rows are generated by a different code path.
    err_orig = (d["oldbalanceOrg"] - d["amount"] - d["newbalanceOrig"]).abs()

    s = pd.DataFrame({"n": d["src"], "drain": drain,
                      "emptied": emptied, "err": np.log1p(err_orig)})
    sg = s.groupby("n")
    send = pd.DataFrame({
        "drain_mean": sg["drain"].mean(),
        "drain_max": sg["drain"].max(),
        "emptied_rate": sg["emptied"].mean(),
        "bal_err_orig": sg["err"].mean(),
        "bal_start": np.log1p(d.groupby("src")["oldbalanceOrg"].first().clip(lower=0)),
    })

    # --- as receiver -----------------------------------------------------
    # pass-through ratio: of everything that arrived, how much was NOT kept.
    # Near 1.0 with a high transaction count is the mule signature.
    kept = (d["newbalanceDest"] - d["oldbalanceDest"]).clip(lower=0)
    passthru = 1.0 - (kept / (d["amount"] + eps)).clip(0, 1)
    err_dest = (d["oldbalanceDest"] + d["amount"] - d["newbalanceDest"]).abs()

    r = pd.DataFrame({"n": d["dst"], "passthru": passthru,
                      "err": np.log1p(err_dest)})
    rg = r.groupby("n")
    recv = pd.DataFrame({
        "passthru_mean": rg["passthru"].mean(),
        "passthru_max": rg["passthru"].max(),
        "bal_err_dest": rg["err"].mean(),
        "bal_end": np.log1p(d.groupby("dst")["newbalanceDest"].last().clip(lower=0)),
    })

    bal = (pd.DataFrame(index=np.arange(n_accounts)).join(send).join(recv))

    # merchants (name starts with 'M') never carry balances in PaySim, so their
    # zeros are structural absence, not observed behaviour. Flag them so the
    # model can tell "no balance data" apart from "balance is genuinely zero".
    is_merchant = np.zeros(n_accounts, dtype=np.float32)
    m_idx = d.loc[d["nameDest"].astype(str).str.startswith("M"), "dst"].unique()
    is_merchant[m_idx] = 1.0
    bal["is_merchant"] = is_merchant

    return bal.fillna(0.0)


def load_paysim(root=None, nrows: int | None = None) -> GraphBundle:
    root = raw_dir("paysim") if root is None else root
    csvs = sorted(root.rglob("*.csv"))
    if not csvs:
        raise FileNotFoundError(f"no CSV under {root}; see docs/DATASETS.md")
    log.info("reading paysim from %s", csvs[0].name)
    df = pd.read_csv(csvs[0], nrows=nrows)

    # account node table: union of origin and destination names
    accounts = pd.Index(pd.unique(pd.concat([df["nameOrig"], df["nameDest"]])))
    idx = pd.Series(np.arange(len(accounts)), index=accounts)
    df["src"] = df["nameOrig"].map(idx).astype(int)
    df["dst"] = df["nameDest"].map(idx).astype(int)

    # ---- per-account transaction aggregates --------------------------------
    out = df.groupby("src").agg(out_cnt=("amount", "size"),
                                out_sum=("amount", "sum"),
                                out_mean=("amount", "mean"),
                                out_max=("amount", "max"))
    inc = df.groupby("dst").agg(in_cnt=("amount", "size"),
                                in_sum=("amount", "sum"),
                                in_mean=("amount", "mean"),
                                in_max=("amount", "max"))
    feat = (pd.DataFrame(index=np.arange(len(accounts)))
            .join(out).join(inc).fillna(0.0))
    # log-scale the heavy-tailed money columns
    for c in list(feat.columns):
        if c.endswith(("_sum", "_mean", "_max")):
            feat[c] = np.log1p(feat[c])
    feat["net_flow"] = feat["in_sum"] - feat["out_sum"]
    feat["degree"] = feat["in_cnt"] + feat["out_cnt"]

    # ---- balance-derived mule features -------------------------------------
    feat = feat.join(_balance_features(df, len(accounts))).fillna(0.0)

    # an account is fraudulent if it originated any fraudulent transaction
    fraud_src = df.loc[df["isFraud"] == 1, "src"].unique()
    y = np.zeros(len(accounts), dtype=int)
    y[fraud_src] = 1

    # account "time" = first step it appears in
    first_step = (pd.concat([df[["src", "step"]].rename(columns={"src": "n"}),
                             df[["dst", "step"]].rename(columns={"dst": "n"})])
                  .groupby("n")["step"].min())
    t = first_step.reindex(np.arange(len(accounts))).fillna(0).astype(int).to_numpy()

    b = GraphBundle(name="paysim", target_node_type="account")
    b.nodes["account"] = pd.DataFrame({"node_id": accounts.astype(str)})
    b.edges[("account", "sent_to", "account")] = df[["src", "dst"]].reset_index(drop=True)
    b.features["account"] = feat.to_numpy(dtype=np.float32)
    b.labels["account"] = y
    b.time["account"] = t
    return b
